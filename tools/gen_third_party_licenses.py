"""Generate THIRD_PARTY_LICENSES: runtime dependencies (Python + npm) and their licenses.

Run with the backend's interpreter so that its installed packages are listed:

    web\\backend\\venv_win\\Scripts\\python.exe tools\\gen_third_party_licenses.py

npm production dependencies are read from `npm ls --omit=dev` in web/frontend.
"""

import json
import subprocess
from importlib.metadata import distributions
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "web" / "frontend"
SKIP = {"pip", "setuptools", "wheel"}


def python_license(meta) -> str:
    if meta.get("License-Expression"):
        return meta["License-Expression"]
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return " / ".join(classifiers)
    return (meta.get("License") or "UNKNOWN").splitlines()[0][:80]


def python_url(meta) -> str:
    urls = [u.split(",", 1)[-1].strip() for u in meta.get_all("Project-URL") or []]
    return meta.get("Home-page") or (urls[0] if urls else "")


def python_rows():
    rows = {}
    for d in distributions():
        m = d.metadata
        if m["Name"].lower() in SKIP:
            continue
        rows[m["Name"].lower()] = (m["Name"], m["Version"], python_license(m), python_url(m))
    return sorted(rows.values(), key=lambda r: r[0].lower())


def npm_rows():
    out = subprocess.run("npm ls --omit=dev --all --json --long", cwd=FRONTEND, shell=True,
                         capture_output=True, text=True, encoding="utf-8").stdout
    seen = {}

    def walk(deps):
        for name, info in (deps or {}).items():
            if name in seen or info.get("missing") or not info.get("version"):
                continue  # optional peer dependency that is not installed
            pkg_json = Path(info.get("path") or FRONTEND / "node_modules" / name) / "package.json"
            lic, url = "UNKNOWN", ""
            if pkg_json.exists():
                pkg = json.loads(pkg_json.read_text(encoding="utf-8"))
                lic = pkg.get("license") or "UNKNOWN"
                if isinstance(lic, dict):
                    lic = lic.get("type", "UNKNOWN")
                if lic == "UNKNOWN" or lic.startswith("SEE LICENSE"):
                    lic = license_from_file(pkg_json.parent) or lic
                repo = pkg.get("repository") or ""
                url = pkg.get("homepage") or (repo.get("url", "") if isinstance(repo, dict) else repo)
            seen[name] = (name, info.get("version", "?"), OVERRIDES.get(name, lic), url)
            walk(info.get("dependencies"))

    walk(json.loads(out).get("dependencies"))
    return sorted(seen.values(), key=lambda r: r[0].lower())


# Packages that declare no license at all: state what is known, never guess.
OVERRIDES = {
    "@mapbox/jsonlint-lines-primitives": "UNDECLARED (fork of zaach/jsonlint, MIT)",
}

LICENSE_MARKERS = {
    "Permission is hereby granted, free of charge": "MIT",
    "Redistribution and use in source and binary forms": "BSD",
    "Apache License": "Apache-2.0",
    "Permission to use, copy, modify, and/or distribute": "ISC",
}


def license_from_file(folder: Path) -> str:
    """Best-effort guess from the LICENSE file when package.json does not declare one.
    The FIRST marker in the file wins: bundled third-party notices come after the main license."""
    for f in folder.iterdir():
        if f.name.upper().startswith(("LICENSE", "LICENCE")):
            text = f.read_text(encoding="utf-8", errors="ignore")
            found = sorted((text.find(k), v) for k, v in LICENSE_MARKERS.items() if k in text)
            if found:
                lic = found[0][1]
                if lic == "BSD":
                    lic = "BSD-3-Clause" if "Neither the name" in text else "BSD-2-Clause"
                return lic
    return ""


def table(rows):
    w = [max(len(str(r[i])) for r in rows) for i in range(3)]
    return "\n".join(f"{n:<{w[0]}}  {v:<{w[1]}}  {lic:<{w[2]}}  {url}".rstrip() for n, v, lic, url in rows)


def main():
    py, js = python_rows(), npm_rows()
    text = f"""THIRD-PARTY SOFTWARE NOTICES
============================

Plotter is licensed under the Apache License 2.0 (see LICENSE and NOTICE).
It uses the third-party open-source packages listed below, each distributed
under its own license. The full license text of each package ships with the
package itself (Python: *.dist-info/; npm: node_modules/<package>/LICENSE).
Only runtime dependencies are listed; development tools (pytest, ruff, ESLint,
Vite, Vitest...) are not distributed.

Generated by tools/gen_third_party_licenses.py — do not edit by hand.


Backend — Python packages ({len(py)})
-----------------------------------

{table(py)}


Frontend — npm packages bundled in web/frontend/dist ({len(js)})
------------------------------------------------------------

{table(js)}
"""
    (ROOT / "THIRD_PARTY_LICENSES").write_text(text, encoding="utf-8")
    print(f"OK: {len(py)} Python + {len(js)} npm packages -> THIRD_PARTY_LICENSES")


if __name__ == "__main__":
    main()
